
// Datatypes

#include <iostream>
using namespace std;

int main (){

    int age = 20 ;               
    float height = 6.4f ;          
    char grade = 'B';
    string name = "Mahdev" ;
    double price = 87.876 ;
    bool pass = false ;

    cout << "Age:" << age << endl ;
    cout << "Height:" << height << endl;
    cout << "Grade:" << grade << endl ;
    cout << "Name:" << name << endl ;
    cout << "Price:" << price << endl ;
    cout << "Pass:" << pass << endl ;

    return 0;
}

// int , float , char , double , bool , string all are datatypes ..